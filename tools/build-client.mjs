import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../t3-session-sidebar/', import.meta.url);
const modules = [
  { file: 'remote-transport.js', name: 'transport', exports: ['createDeviceConnection'] },
  { file: 'device-realm.js', name: 'realm', exports: ['createDeviceRealm'] },
  { file: 'shortcuts-bridge.js', name: 'shortcuts', exports: ['createShortcutRouter'] },
  { file: 'remote-runtime.js', name: 'runtime', exports: ['createDeviceRuntimePool', 'createDeferredNavigation', 'createRuntimeLayout', 'nativeRosterOf'] },
];
const pieces = [];
for (const module of modules) {
  let source = await readFile(new URL(module.file, root), 'utf8');
  source = source.replace(/^import \{ createDeviceConnection \} from '\.\/remote-transport\.js';\n/m, '');
  source = source.replace(/^import \{ createDeviceRealm \} from '\.\/device-realm\.js';\n/m, '');
  source = source.replace(/^import \{ createShortcutRouter \} from '\.\/shortcuts-bridge\.js';\n/m, '');
  source = source.replace(/^export (?=(?:async )?function |const |class )/gm, '');
  if (/^(?:import|export) /m.test(source)) throw new Error(`Unsupported module syntax in ${module.file}`);
  const dependencies = module.name === 'runtime'
    ? 'const { createDeviceConnection } = transport;\nconst { createDeviceRealm } = realm;\nconst { createShortcutRouter } = shortcuts;\n' : '';
  pieces.push(`const ${module.name} = (() => {\n${dependencies}${source}\nreturn { ${module.exports.join(', ')} };\n})();`);
}
const output = `// Generated by tools/build-client.mjs. Edit the ESM source modules.\nwindow.__ModuleLoader__.load({\n  id: '@local/dsh-t3-session-sidebar',\n  chunk: 'client.remote-runtime.js',\n  factory(require) {\n'use strict';\n${pieces.join('\n')}\nreturn runtime;\n  }\n});\n`;
const target = new URL('client.remote-runtime.js', root);
if (process.argv.includes('--check')) {
  const existing = await readFile(target, 'utf8');
  if (existing !== output) throw new Error('The device runtime chunk is stale; run node tools/build-client.mjs');
  console.log('Device runtime chunk matches its sources.');
} else {
  await writeFile(target, output);
  console.log(`Built ${fileURLToPath(target)} (${Buffer.byteLength(output)} bytes).`);
}
